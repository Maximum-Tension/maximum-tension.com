/* LOCAL STORAGE CAN THROW (PRIVATE WINDOWS, BLOCKED SITE DATA): NEVER LET IT */
function
	storage_get(key)
{
	try
	{
		if (LOCAL_STORAGE.CHECK(key))
			return (LOCAL_STORAGE.GET(key));
	}
	catch (error) {}

	return (undefined);
}

function
	storage_set(key, value)
{
	try
	{
		LOCAL_STORAGE.SET(key, value);
	}
	catch (error) {}
}

/*
** ENGLISH BY DEFAULT. VISITORS IN TURKEY (TURKISH TIME ZONE, OR A BROWSER
** SET TO TURKISH) GET TURKISH. A LANGUAGE PICKED FROM THE MENU WINS OVER
** BOTH AND IS REMEMBERED.
*/
function
	detect_language()
{
	var		zone = "";
	var		browser = (navigator.language || navigator.userLanguage || "").toLowerCase();

	try
	{
		zone = Intl.DateTimeFormat().resolvedOptions().timeZone || "";
	}
	catch (error) {}

	if (zone === "Europe/Istanbul" || zone === "Asia/Istanbul" || browser.substring(0, 2) === "tr")
		return ("tr");

	return ("en");
}

if (lang_table[storage_get("lang")])
	lang = storage_get("lang");
else
	lang = detect_language();

